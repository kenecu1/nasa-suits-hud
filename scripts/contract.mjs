// npm run contract              regenerate client/src/contract.gen.ts from backend/suits/contract.py
// npm run contract -- --check   fail if the committed file is out of date (drift check)
// --out <path>                  write or check another file (used by the drift test)
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { compile } from "json-schema-to-typescript";
import { ROOT, venvPython } from "./py.mjs";

const args = process.argv.slice(2);
const check = args.includes("--check");
const outIndex = args.indexOf("--out");
const out = outIndex >= 0 ? args[outIndex + 1] : join(ROOT, "client", "src", "contract.gen.ts");
if (!out) {
  console.error("--out needs a path");
  process.exit(2);
}

const BANNER = [
  "// Generated by `npm run contract` from backend/suits/contract.py. Do not edit by hand.",
  "// Contract v2: State is sent backend -> client as JSON text on /ws.",
].join("\n");

const py = spawnSync(venvPython(), ["-m", "suits.contract"], { cwd: ROOT, encoding: "utf8" });
if (py.status !== 0) {
  console.error(py.stderr);
  process.exit(py.status ?? 1);
}

const schema = JSON.parse(py.stdout);
const generated = await compile(schema, "SuitsContract", {
  bannerComment: BANNER,
  additionalProperties: false,
  unreachableDefinitions: true,
  strictIndexSignatures: true,
  style: { singleQuote: false, semi: true, printWidth: 100 },
});

const normalise = (text) => text.replace(/\r\n/g, "\n");
const shown = relative(ROOT, out);

if (check) {
  if (!existsSync(out)) {
    console.error(`${shown} is missing. Run \`npm run contract\`.`);
    process.exit(1);
  }
  if (normalise(readFileSync(out, "utf8")) !== normalise(generated)) {
    console.error(`${shown} is out of date with backend/suits/contract.py. Run \`npm run contract\`.`);
    process.exit(1);
  }
  console.log(`${shown} is up to date.`);
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, normalise(generated));
  console.log(`wrote ${shown}`);
}
